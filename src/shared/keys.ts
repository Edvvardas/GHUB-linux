export function browserCodeToLinux(code:string):string|null { return BROWSER_CODES[code] ?? null; }
export function keyLabel(key:string):string {
 const aliases:Record<string,string>={KEY_LEFT:'← Left',KEY_RIGHT:'Right →',KEY_UP:'↑ Up',KEY_DOWN:'↓ Down',KEY_LEFTCTRL:'Left Ctrl',KEY_RIGHTCTRL:'Right Ctrl',KEY_LEFTALT:'Left Alt',KEY_RIGHTALT:'Right Alt',KEY_LEFTSHIFT:'Left Shift',KEY_RIGHTSHIFT:'Right Shift',KEY_LEFTMETA:'Left Super',KEY_RIGHTMETA:'Right Super',BTN_LEFT:'Left click',BTN_RIGHT:'Right click',BTN_MIDDLE:'Middle click',BTN_SIDE:'Mouse 4',BTN_EXTRA:'Mouse 5'};
 return aliases[key] ?? key.replace(/^KEY_/, '').replace(/^KP/, 'Numpad ').replaceAll('_',' ');
}
/** Capture a single physical chord; releases use code identity, never layout text. */
export class ChordCapture {
 keys:string[]=[]; held=new Map<string,string>(); error:string|null=null;
 press(code:string,repeat=false) {
  if(repeat)return;
  if(this.held.size===0){this.keys=[];this.error=null;}
  const key=browserCodeToLinux(code);
  if(!key){this.error='This key is not supported';this.held.set(code,'');return;}
  if(this.held.has(code))return;
  this.held.set(code,key);
  if(this.keys.length>=8){this.error='Use at most eight keys';return;}
  this.keys.push(key);
 }
 release(code:string){this.held.delete(code);}
 get ready(){return this.keys.length>0&&this.held.size===0&&!this.error;}
 cancel(){this.keys=[];this.held.clear();this.error=null;}
}
